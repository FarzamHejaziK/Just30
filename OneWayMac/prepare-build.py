#!/usr/bin/env python3
"""Prepare consistent app/helper identities without committing account settings."""
import argparse
import json
import os
import plistlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def config(unsigned=False):
    local = ROOT / ".signing.json"
    saved = {} if unsigned or not local.exists() else json.loads(local.read_text())
    team = "UNSIGNED" if unsigned else os.getenv("ONEWAY_TEAM_ID", saved.get("teamID", ""))
    identity = "-" if unsigned else os.getenv("ONEWAY_SIGNING_IDENTITY", saved.get("signingIdentity", ""))
    app = "dev.oneway.mac.preview" if unsigned else os.getenv("ONEWAY_BUNDLE_ID", saved.get("bundleIdentifier", "dev.oneway.mac"))
    if not unsigned and (not re.fullmatch(r"[A-Z0-9]{10}", team) or not identity or team == "YOUR_TEAM_ID"):
        raise ValueError("Copy .signing.example.json to .signing.json and supply your team ID and Developer ID Application identity. Use --unsigned for compilation/UI preview only.")
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9-]*(?:\.[A-Za-z0-9-]+)+", app):
        raise ValueError("bundleIdentifier must be a valid reverse-DNS identifier")
    return team, identity, app


def prepare(build: Path, unsigned: bool):
    team, identity, app_id = config(unsigned)
    contents = build / "JustThirty.app" / "Contents"
    generated = build / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    (contents / "Library/LaunchDaemons").mkdir(parents=True, exist_ok=True)
    for source, destination in [
        ("Info.plist", contents / "Info.plist"),
        ("HelperInfo.plist", generated / "HelperInfo.plist"),
        ("OneWayHelper.plist", contents / "Library/LaunchDaemons" / (app_id + ".helper.plist")),
    ]:
        text = (ROOT / "Resources" / source).read_text().replace("dev.oneway.mac", app_id)
        document = plistlib.loads(text.encode())
        destination.write_bytes(plistlib.dumps(document))
    (generated / "BuildIdentity.swift").write_text(
        "// Generated by prepare-build.py; never commit signing configuration.\n"
        "enum OneWayBuildIdentity {\n"
        f"    static let appID = {json.dumps(app_id)}\n"
        f"    static let teamID = {json.dumps(team)}\n"
        "}\n"
    )
    (generated / "signing-identity").write_text(identity)
    (generated / "helper-identifier").write_text(app_id + ".helper")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--unsigned", action="store_true")
    args = parser.parse_args()
    try:
        prepare(args.build, args.unsigned)
    except (ValueError, OSError) as error:
        parser.exit(2, str(error) + "\n")
